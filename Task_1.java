package task;

public class Task_1 {
	 public static void main(String[] args) {
		 
		 System.out.println("1. Square Root: " + Math.sqrt(25));
	     System.out.println("2. Power: " + Math.pow(2, 3));
	     System.out.println("3. Absolute Value: " + Math.abs(-15));
	     System.out.println("4. Floor: " + Math.floor(10.8));
	     System.out.println("5. Ceil: " + Math.ceil(10.2));
	     System.out.println("6. Round: " + Math.round(10.6));
	     System.out.println("7. Maximum: " + Math.max(25, 40));
	     System.out.println("8. Minimum: " + Math.min(25, 40));
	     System.out.println("9. Random Number (1-100): "+ ((int) (Math.random() * 100) + 1));
	     System.out.println("10. Sine: " + Math.sin(Math.toRadians(30)));
	     System.out.println("11. Cosine: " + Math.cos(Math.toRadians(60)));
	     System.out.println("12. Tangent: " + Math.tan(Math.toRadians(45)));
	     System.out.println("13. Logarithm: " + Math.log(10));
	     System.out.println("14. Exponential: " + Math.exp(2));
	     System.out.println("15. Cube Root: " + Math.cbrt(27));
	}

}
