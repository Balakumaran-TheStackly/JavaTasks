package day2;

public class Task2_swap {
	public static void main(String[] args) {
		int a=10;
		int b=20;
		int temp=0;
		System.out.println("Before Swap: a = " + a + ", b = " + b);
		//Swapping values of Variables
		temp=a;
		a=b;
		b=temp;
		
		System.out.println("After Swap: a = " + a + ", b = " + b);
		
		
	}

}
